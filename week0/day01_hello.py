# ---- 第三步：第一行 ----
print("你好")


# ---- 第四步：数字和文字的区别 ----
# 带引号的是文字，不带引号的是数字。
# 文字相加是拼接，数字相加是算术。
print(1 + 1)
print("1" + "1")
print("你好" + "世界")


# ---- 加餐：程序可以问你问题 ----
# input() 会停下来等你打字，按回车才继续。
# 这一行如果不想每次都输入，可以先在前面加 # 注释掉。
name = input("你叫什么名字？")
print("你好，" + name)


